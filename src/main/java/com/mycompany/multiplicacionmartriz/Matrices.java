     private void txtTamanoKeyTyped(java.awt.event.KeyEvent evt) {
    char c = evt.getKeyChar();

    if (!Character.isDigit(c)) {
        evt.consume(); // No permite el carácter

        Toolkit.getDefaultToolkit().beep();

        JOptionPane.showMessageDialog(this,
                "Solo se permiten números.");
    }
}
private void validarTabla(javax.swing.JTable tabla) {

    tabla.getModel().addTableModelListener(e -> {

        int fila = e.getFirstRow();
        int columna = e.getColumn();

        Object valor = tabla.getValueAt(fila, columna);

        if (valor == null) return;

        try {

            Double.parseDouble(valor.toString());

        } catch (NumberFormatException ex) {

            tabla.setValueAt(null, fila, columna);

            JOptionPane.showMessageDialog(this,
                    "Solo se permiten números");
        }
    });
}
