    private void jTextField1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jTextField1ActionPerformed

    int n = Integer.parseInt(jTextField1.getText());

    String[] columnas = new String[n + 1];

    columnas[0] = "";

    for (int i = 1; i <= n; i++) {
        columnas[i] = "C" + i;
    }

    DefaultTableModel modeloA = new DefaultTableModel(columnas, n) {
    @Override
    public boolean isCellEditable(int fila, int columna) {
        return columna != 0; // La columna F no se puede editar
        }
    };
    DefaultTableModel modeloB = new DefaultTableModel(columnas, n) {
    @Override
    public boolean isCellEditable(int fila, int columna) {
        return columna != 0; // La columna F no se puede editar
    }
};
    
    for (int i = 0; i < n; i++) {
        modeloA.setValueAt("F" + (i + 1), i, 0);
        modeloB.setValueAt("F" + (i + 1), i, 0);
    }

    tblMatrizA.setModel(modeloA);
    tblMatrizB.setModel(modeloB);

    validarTabla(tblMatrizA);
    validarTabla(tblMatrizB);
    }//GEN-LAST:event_jTextField1ActionPerformed

