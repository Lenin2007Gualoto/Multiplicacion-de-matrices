    private void btnMultiplicarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMultiplicarActionPerformed
        
    int n = tblMatrizA.getRowCount();

    String[] columnas = new String[n + 1];
    columnas[0] = "";

    for (int i = 1; i <= n; i++) {
        columnas[i] = "C" + i;
    }

    DefaultTableModel modeloR = new DefaultTableModel(columnas, n);
    
    // Etiquetas F1, F2, F3...
    for (int i = 0; i < n; i++) {
        modeloR.setValueAt("F" + (i + 1), i, 0);
    }

    double[][] A = new double[n][n];
    double[][] B = new double[n][n];
    double[][] R = new double[n][n];

    // Leer Matriz A
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {

            Object valor = tblMatrizA.getValueAt(i, j + 1);

            if (valor == null || valor.toString().trim().isEmpty()) {
                valor = "0";
            }

            A[i][j] = Double.parseDouble(valor.toString());
        }
    }

    // Leer Matriz B
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {

            Object valor = tblMatrizB.getValueAt(i, j + 1);

            if (valor == null || valor.toString().trim().isEmpty()) {
                valor = "0";
            }

            B[i][j] = Double.parseDouble(valor.toString());
        }
    }

    // Multiplicación de matrices
    for (int i = 0; i < n; i++) {

        for (int j = 0; j < n; j++) {

            R[i][j] = 0;

            for (int k = 0; k < n; k++) {

                R[i][j] += A[i][k] * B[k][j];

            }
        }
    }

    // Mostrar resultado
    for (int i = 0; i < n; i++) {

        for (int j = 0; j < n; j++) {

            modeloR.setValueAt(R[i][j], i, j + 1);

        }
    }

    tblResultado.setModel(modeloR);
    TableRowSorter<DefaultTableModel> sorter =
        new TableRowSorter<>((DefaultTableModel) tblResultado.getModel());

tblResultado.setRowSorter(sorter);
    }//GEN-LAST:event_btnMultiplicarActionPerformed

